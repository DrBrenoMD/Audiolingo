/**
 * Returns instantaneous dictionary entry for common English words in 0ms.
 */
export function getInstantWordLookup(cleanWord: string, contextSentence: string = ''): WordLookupResult | null {
  const normalized = cleanWord.toLowerCase().trim();
  const entry = INSTANT_DICTIONARY[normalized];
  if (!entry) return null;

  return {
    word: cleanWord,
    phonetic: entry.ipa,
    phoneticIpa: entry.ipa,
    cefrLevel: 'B1',
    translationPt: entry.translationPt,
    partOfSpeech: entry.pos,
    contextualExplanation: `Na passagem do audiolivro, '${cleanWord}' traduz-se comumente como '${entry.translationPt}'.`,
    definitions: [
      {
        pos: entry.pos,
        englishDef: `Commonly used ${entry.pos} meaning: ${entry.translationPt}`,
        portugueseDef: entry.definitionPt,
      },
    ],
    synonyms: [],
    antonyms: [],
    collocations: [`the ${cleanWord}`, `${cleanWord} in`],
    examples: contextSentence
      ? [{ en: contextSentence, pt: `Tradução contextual da frase com '${entry.translationPt}'.` }]
      : [{ en: `This is an example with ${cleanWord}.`, pt: `Este é um exemplo com ${entry.translationPt}.` }],
    grammarNotes: `Palavra em inglês: '${cleanWord}'. Classe gramatical: ${entry.pos}.`,
    source: 'traditional_api',
  };
}
