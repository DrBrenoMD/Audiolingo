// Helper to build word cues with start/end relative to sentence
function buildWordCues(text: string, sentenceStart: number, sentenceEnd: number): WordCue[] {
  const rawWords = text.trim().split(/\s+/);
  const totalDuration = sentenceEnd - sentenceStart;
  const wordDuration = totalDuration / rawWords.length;

  return rawWords.map((rawWord, idx) => {
    const cleanWord = rawWord.replace(/[^a-zA-Z0-9']/g, '').toLowerCase();
    const start = +(sentenceStart + idx * wordDuration).toFixed(2);
    const end = +(sentenceStart + (idx + 1) * wordDuration).toFixed(2);
    return {
      word: rawWord,
      cleanWord: cleanWord || rawWord.toLowerCase(),
      start,
      end,
      index: idx,
    };
  });
}

